SET NOCOUNT ON;
IF OBJECT_ID('tempdb..#dp_row_counts') IS NOT NULL DROP TABLE #dp_row_counts;
CREATE TABLE #dp_row_counts (TBL VARCHAR(30) NOT NULL, ROW_COUNT BIGINT NOT NULL) WITH (DISTRIBUTION = ROUND_ROBIN, HEAP);
INSERT INTO #dp_row_counts (TBL, ROW_COUNT)
SELECT 'CUSTOMER_SEGMENTS', COUNT_BIG(*) FROM dp.CUSTOMER_SEGMENTS
UNION ALL SELECT 'TRANSACTION_ANALYTICS', COUNT_BIG(*) FROM dp.TRANSACTION_ANALYTICS
UNION ALL SELECT 'CUSTOMER_RISK_SCORES', COUNT_BIG(*) FROM dp.CUSTOMER_RISK_SCORES
UNION ALL SELECT 'CUSTOMER_MASTER_PROFILE', COUNT_BIG(*) FROM dp.CUSTOMER_MASTER_PROFILE;
SELECT TBL, ROW_COUNT FROM #dp_row_counts ORDER BY TBL;
DECLARE @empty_tables VARCHAR(400) = (SELECT STRING_AGG(TBL, ', ') FROM #dp_row_counts WHERE ROW_COUNT = 0);
IF @empty_tables IS NOT NULL
BEGIN
    DECLARE @msg NVARCHAR(2048) = CONCAT('Post-run validation failed: 0 rows in dp.', @empty_tables);
    DROP TABLE #dp_row_counts;
    THROW 50098, @msg, 1;
END;
DROP TABLE #dp_row_counts;
